const css = readFileSync(join(ROOT, "assets/css/tokens.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const declarations = new Map([...css.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));

function resolve(value, theme) {
  const lightDark = value.match(/^light-dark\((.+),\s*(.+)\)$/);
  if (lightDark) return resolve(lightDark[theme === "light" ? 1 : 2].trim(), theme);
  const reference = value.match(/^var\(--([\w-]+)\)$/);
  if (reference) {
    if (!declarations.has(reference[1])) throw new Error(`Unknown token --${reference[1]}`);
    return resolve(declarations.get(reference[1]), theme);
  }
  if (/^#[0-9a-f]{6}$/i.test(value)) return value.toLowerCase();
  throw new Error(`Cannot resolve "${value}" to a hex color`);
}

function luminance(hex) {
  const channels = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const [r, g, b] = channels.map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function ratio(a, b) {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
}

const rows = [];
let failures = 0;
for (const [fg, bg, required, themes = ["light", "dark"]] of PAIRS) {
  const cells = ["light", "dark"].map((theme) => {
    if (!themes.includes(theme)) return "not used";
    const value = ratio(resolve(declarations.get(fg), theme), resolve(declarations.get(bg), theme));
    if (value < required) failures++;
    return `${value.toFixed(2)} ${value >= required ? "pass" : "FAIL"}`;
  });
  rows.push(`| \`--${fg}\` | \`--${bg}\` | ${required}:1 | ${cells[0]} | ${cells[1]} |`);
}

const report = `# Contrast Report

Generated by \`tools/contrast.mjs\` from \`assets/css/tokens.css\`. Do not edit by hand.
Text pairs need 4.5:1. UI pairs (control borders, focus ring, status icons, chart marks) need 3:1.
\`--border\` is decorative (cards, dividers) and is not checked; controls are bounded by \`--input\`.

| Foreground | Background | Needs | Light | Dark |
|---|---|---|---|---|
${rows.join("\n")}

Result: ${failures === 0 ? "all pairs pass" : `${failures} failing pair(s)`}.
`;

writeFileSync(join(ROOT, "contrast-report.md"), report);
if (failures) {
  console.error(`Contrast check failed: ${failures} failing pair(s). See contrast-report.md.`);
  process.exit(1);
}
console.log(`Contrast check passed: ${PAIRS.length} pairs in 2 themes.`);
